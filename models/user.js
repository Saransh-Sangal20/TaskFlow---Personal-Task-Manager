const mongoose = require("mongoose");

const userSchema = new mongoose.Schema({
    username: {
        type: String,
        required: true,
        unique: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    }
});  // schema for user model

const User = mongoose.model("User", userSchema);  // creating user model
module.exports = User;  // exporting user model